import test from 'node:test';
import assert from 'node:assert/strict';
import fc from 'fast-check';
import * as api from '../src/index.ts';
const A = api as any;
function value(r: any): any { assert.equal(r.ok, true, JSON.stringify(r)); return r.value; }
const context = () => value(api.withDeadline({timeoutMs: 10000}));
function claim(namespace = [1], key = [2], retainUntil = 100) { return value(A.Claim.create({namespace: new Uint8Array(namespace), key: new Uint8Array(key), retainUntil})); }
test('fresh equal-byte arrays claim once and duplicate retention never extends', async () => {
  assert.equal(typeof A.createMemoryStore, 'function');
  const store = value(A.createMemoryStore({maxEntries: 2}));
  assert.equal(A.isReplayStore(store), true);
  assert.equal(Object.isFrozen(store), true);
  assert.equal(value(await store.claim(claim(), context())), 'claimed');
  assert.equal(value(await store.claim(claim([1], [2], 200), context())), 'already_claimed');
  assert.equal(value(await store.sweep(99, context())), 0);
  assert.equal(value(await store.sweep(100, context())), 1);
  assert.equal(value(await store.claim(claim(), context())), 'claimed');
});
test('memory namespaces and keys cannot collide and exact capacity rejects without eviction', async () => {
  assert.equal(typeof A.createMemoryStore, 'function');
  const store = value(A.createMemoryStore({maxEntries: 2}));
  assert.equal(value(await store.claim(claim([1], [2,3]), context())), 'claimed');
  assert.equal(value(await store.claim(claim([1,2], [3]), context())), 'claimed');
  assert.equal(value(await store.claim(claim([1], [2,3]), context())), 'already_claimed');
  assert.equal((await store.claim(claim([2], [1]), context())).error.reason, 'store_full');
  assert.equal(value(await store.sweep(100, context())), 2);
  assert.equal(value(await store.claim(claim([2], [1]), context())), 'claimed');
});
test('64 concurrent memory claims yield one winner', async () => {
  assert.equal(typeof A.createMemoryStore, 'function');
  const store = value(A.createMemoryStore({maxEntries: 1}));
  const results = await Promise.all(Array.from({length: 64}, () => store.claim(claim(), context())));
  assert.equal(results.filter(r => value(r) === 'claimed').length, 1);
  assert.equal(results.filter(r => value(r) === 'already_claimed').length, 63);
});
test('memory idempotence and monotone sweep hold for generated byte identities', async () => {
  assert.equal(typeof A.createMemoryStore, 'function');
  await fc.assert(fc.asyncProperty(fc.uint8Array({minLength: 1, maxLength: 256}), fc.uint8Array({minLength: 1, maxLength: 256}), fc.integer({min: 1, max: 253402300799}), async (namespace, key, end) => {
    const store = value(A.createMemoryStore({maxEntries: 1}));
    const c = () => value(A.Claim.create({namespace: new Uint8Array(namespace), key: new Uint8Array(key), retainUntil: end}));
    assert.equal(value(await store.claim(c(), context())), 'claimed');
    assert.equal(value(await store.claim(c(), context())), 'already_claimed');
    assert.equal(value(await store.sweep(end - 1, context())), 0);
    assert.equal(value(await store.sweep(end, context())), 1);
    assert.equal(value(await store.sweep(end, context())), 0);
  }), {seed: 6402, numRuns: 300});
});
test('invalid memory inputs and expired contexts cannot insert or sweep', async () => {
  assert.equal(typeof A.createMemoryStore, 'function');
  for (const input of [{}, {maxEntries: 0}, {maxEntries: 10000001}, {maxEntries: 1, unknown: true}]) assert.equal(A.createMemoryStore(input).ok, false);
  const store = value(A.createMemoryStore({maxEntries: 1}));
  assert.equal((await store.claim({...claim()}, context())).error.reason, 'invalid_claim');
  const controller = new AbortController(); controller.abort();
  const c = value(api.withDeadline({signal: controller.signal}));
  assert.equal((await store.claim(claim(), c)).error.reason, 'store_timeout');
  assert.equal(value(await store.sweep(100, context())), 0);
  assert.equal(value(await store.claim(claim(), context())), 'claimed');
  for (const now of [-1, 253402300800, NaN, '0']) assert.equal((await store.sweep(now, context())).error.reason, 'invalid_options');
  assert.equal((await store.sweep(100, c)).error.reason, 'store_timeout');
  assert.equal(value(await store.claim(claim(), context())), 'already_claimed');
  assert.equal(value(await store.sweep(253402300799, context())), 1);
});
test('cancellation before dispatched memory work prevents insertion', async () => {
  const store = value(A.createMemoryStore({maxEntries: 1}));
  const caller = new AbortController();
  const c = value(api.withDeadline({signal: caller.signal}));
  const pending = store.claim(claim(), c);
  caller.abort();
  const result = await pending;
  assert.equal(result.error.reason, 'store_timeout');
  assert.equal(value(await store.sweep(100, context())), 0);
});
